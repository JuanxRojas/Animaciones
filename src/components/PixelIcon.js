export default function PixelIcon({ name, color = COLORS.white, size = 22 }) {
  const pattern = ICONS[name] || ICONS.info;
  const pixelSize = size / 7;

  return (
    <View style={{ width: size, height: size, flexDirection: 'column' }}>
      {pattern.map((line, rowIndex) => (
        <View key={`${name}-${rowIndex}`} style={{ height: pixelSize, flexDirection: 'row' }}>
          {line.split('').map((pixel, columnIndex) => (
            <View
              key={`${name}-${rowIndex}-${columnIndex}`}
              style={{
                width: pixelSize,
                height: pixelSize,
                backgroundColor: pixel === '1' ? color : 'transparent',
              }}
            />
          ))}
        </View>
      ))}
    </View>
  );
}
